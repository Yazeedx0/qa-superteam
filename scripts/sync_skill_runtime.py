#!/usr/bin/env python3
"""Bundle the qast runtime and shared docs into the skills so any agent can use them.

Installers such as `npx skills add` copy only skill folders. This script makes the skill
set self-sufficient:

* skills/using-qa-superteam/scripts/qast           launcher (python3 -I, stdlib only)
* skills/using-qa-superteam/scripts/qa_superteam/  copy of src/qa_superteam (*.py)
* skills/using-qa-superteam/scripts/policies/      copy of policies/*.toml
* skills/using-qa-superteam/scripts/templates/     copy of templates/config.toml
* skills/qa-release-gate/references/policy.md      copy of docs/policy.md
* skills/qa-strategy/references/risk-model.md      copy of docs/risk-model.md

    python3 scripts/sync_skill_runtime.py          # write
    python3 scripts/sync_skill_runtime.py --check  # CI: fail if the bundle drifted from the sources
"""

from __future__ import annotations

import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BUNDLE = ROOT / "skills" / "using-qa-superteam" / "scripts"
HEADER = "<!-- Generated by scripts/sync_skill_runtime.py from {src}; edit the source, not this copy. -->\n\n"

LAUNCHER = """#!/bin/sh
# qast launcher bundled with the using-qa-superteam skill (generated by scripts/sync_skill_runtime.py).
# Works wherever the skill folder was installed: runs the stdlib-only core in isolated mode.
set -e
case "$0" in
  */*) here="${0%/*}" ;;
  *) here="$(dirname "$(command -v "$0")")" ;;
esac
here="$(cd "$here" && pwd -P)"
QAST_PLUGIN_ROOT="$here"
export QAST_PLUGIN_ROOT
exec "${QAST_PYTHON:-python3}" -I -c 'import sys; sys.path.insert(0, sys.argv.pop(1)); from qa_superteam.cli import main; sys.exit(main())' "$here" "$@"
"""


def expected() -> dict[Path, bytes]:
    files: dict[Path, bytes] = {BUNDLE / "qast": LAUNCHER.encode()}
    for src in sorted((ROOT / "src" / "qa_superteam").rglob("*.py")):
        files[BUNDLE / "qa_superteam" / src.relative_to(ROOT / "src" / "qa_superteam")] = src.read_bytes()
    for src in sorted((ROOT / "policies").glob("*.toml")):
        files[BUNDLE / "policies" / src.name] = src.read_bytes()
    files[BUNDLE / "templates" / "config.toml"] = (ROOT / "templates" / "config.toml").read_bytes()
    for src, dst in (
        ("docs/policy.md", "skills/qa-release-gate/references/policy.md"),
        ("docs/risk-model.md", "skills/qa-strategy/references/risk-model.md"),
    ):
        files[ROOT / dst] = HEADER.format(src=src).encode() + (ROOT / src).read_bytes()
    return files


def main() -> int:
    check = "--check" in sys.argv
    want = expected()
    existing = {p for p in BUNDLE.rglob("*") if p.is_file() and "__pycache__" not in p.parts} if BUNDLE.exists() else set()
    stale = sorted(existing - set(want) - {BUNDLE / "README.md"})
    drift = [p for p, data in want.items() if not p.exists() or p.read_bytes() != data]
    if check:
        if drift or stale:
            for p in drift + stale:
                print(f"out of date: {p.relative_to(ROOT)}")
            print("run: python3 scripts/sync_skill_runtime.py")
            return 1
        print(f"skill runtime bundle up to date ({len(want)} files)")
        return 0
    for p in stale:
        p.unlink()
    for p, data in want.items():
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_bytes(data)
    (BUNDLE / "qast").chmod(0o755)
    for d in [d for d in BUNDLE.rglob("__pycache__")]:
        shutil.rmtree(d, ignore_errors=True)
    print(f"wrote {len(want)} files")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
